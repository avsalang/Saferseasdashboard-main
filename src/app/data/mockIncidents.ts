function roundCoordinate(value: number) {
  return Math.round(value * 10000) / 10000;
}

function buildIncident(seed: IncidentSeed): Incident {
  const vessel = vesselProfiles[seed.vessel];
  const corridor = corridorProfiles[seed.corridor];
  const [latOffset, lngOffset] = seed.offset ?? [0, 0];

  return {
    id: seed.id,
    date: seed.date,
    type: seed.type,
    casualtyType: seed.casualtyType,
    severity: seed.severity,
    vesselName: vessel.vesselName,
    formerNames: vessel.formerNames,
    vesselType: vessel.vesselType,
    flagState: vessel.flagState,
    imoNumber: vessel.imoNumber,
    officialNumber: vessel.officialNumber,
    grossTonnage: vessel.grossTonnage,
    lengthMeters: vessel.lengthMeters,
    breadthMeters: vessel.breadthMeters,
    propulsionType: vessel.propulsionType,
    enginePowerKw: vessel.enginePowerKw,
    classificationSociety: vessel.classificationSociety,
    yearBuilt: vessel.yearBuilt,
    location: {
      lat: roundCoordinate(corridor.lat + latOffset),
      lng: roundCoordinate(corridor.lng + lngOffset),
      port: corridor.port,
      province: corridor.province,
    },
    seaArea: corridor.seaArea,
    corridor: corridor.corridor,
    weather: seed.weather,
    ownerName: vessel.ownerName,
    ownerContact: vessel.ownerContact,
    operatorName: vessel.operatorName,
    operatorAddress: vessel.operatorAddress,
    voyageOrigin: corridor.voyageOrigin,
    voyageDestination: corridor.voyageDestination,
    intendedRoute: corridor.intendedRoute,
    cargoType: seed.cargoType ?? vessel.cargoType,
    cargoQuantity: seed.cargoQuantity ?? vessel.cargoQuantity,
    authority: seed.authority,
    reportingMethod: seed.reportingMethod,
    status: seed.status,
    narrative: seed.narrative,
    keyEventsTimeline: seed.keyEventsTimeline,
    crewResponse: seed.crewResponse,
    crewBehaviorFactors: seed.crewBehaviorFactors,
    primaryCause: seed.primaryCause,
    findingsOfCause: seed.findingsOfCause,
    damagesIncurred: seed.damagesIncurred,
    crewCount: seed.crewCount ?? vessel.crewCount,
    passengerCount: seed.passengerCount ?? vessel.passengerCount,
    fatalities: seed.fatalities,
    injuries: seed.injuries,
    recommendations: seed.recommendations,
    linkedDocuments: seed.linkedDocuments,
  };
}

