const HISTORICAL_EXPANSION_YEARS = Array.from({ length: 8 }, (_, index) => 2017 + index);
const HISTORICAL_RECORDS_PER_YEAR = 21;
const historicalReviewNotes = [
  "The archived case remained part of corridor trend review.",
  "The record was retained for annual maritime safety comparison.",
  "Review notes linked the event to recurring local operating conditions.",
  "The case was later referenced during periodic route risk review.",
];

function buildHistoricalId(year: number, yearIndex: number, slot: number) {
  const sequence = 500000 + yearIndex * HISTORICAL_RECORDS_PER_YEAR + slot + 1;
  return `INC-${year}-${String(sequence).padStart(6, "0")}`;
}

function shiftDateToYear(dateString: string, year: number, slot: number) {
  const date = new Date(dateString);
  date.setUTCFullYear(year);
  date.setUTCDate(Math.min(28, Math.max(1, date.getUTCDate() + ((slot % 3) - 1))));
  date.setUTCMinutes(date.getUTCMinutes() + slot * 7);
  date.setUTCSeconds(0, 0);
  return date.toISOString();
}

function buildHistoricalOffset(offset: [number, number] | undefined, yearIndex: number, slot: number): [number, number] {
  const [baseLat, baseLng] = offset ?? [0, 0];
  const latJitter = ((((yearIndex + 1) * 3) + slot * 2) % 9 - 4) * 0.0023;
  const lngJitter = ((((yearIndex + 1) * 5) + slot * 3) % 9 - 4) * 0.0021;
  return [baseLat + latJitter, baseLng + lngJitter];
}

function resolveHistoricalStatus(year: number, slot: number) {
  if (year <= 2022) {
    return slot % 4 === 0 ? "Verified" : "Published";
  }

  return slot % 3 === 0 ? "Verified" : "Published";
}

function resolveHistoricalReportingMethod(year: number, slot: number, fallback: string) {
  const options =
    year <= 2018 ? ["Manual Encoding", "Email Intake", "Inter-agency Intake"] :
    year <= 2021 ? ["Email Intake", "Inter-agency Intake", "Web Portal"] :
    ["Web Portal", "Inter-agency Intake", "Mobile App", "Email Intake"];

  return options[(slot + year) % options.length] ?? fallback;
}

function buildHistoricalSeed(template: IncidentSeed, year: number, yearIndex: number, slot: number): IncidentSeed {
  const reviewNote = historicalReviewNotes[(yearIndex + slot) % historicalReviewNotes.length];

  return {
    ...template,
    id: buildHistoricalId(year, yearIndex, slot),
    date: shiftDateToYear(template.date, year, slot),
    offset: buildHistoricalOffset(template.offset, yearIndex, slot),
    reportingMethod: resolveHistoricalReportingMethod(year, slot, template.reportingMethod),
    status: resolveHistoricalStatus(year, slot),
    narrative: `${template.narrative} ${reviewNote}`,
    linkedDocuments: Array.from(new Set([...template.linkedDocuments, "Archived Incident Summary"])),
  };
}

const generatedHistoricalSeeds: IncidentSeed[] = HISTORICAL_EXPANSION_YEARS.flatMap((year, yearIndex) => {
  const startIndex = (yearIndex * 4) % incidentSeeds.length;

  return Array.from({ length: HISTORICAL_RECORDS_PER_YEAR }, (_, slot) => {
    const template = incidentSeeds[(startIndex + slot) % incidentSeeds.length];
    return buildHistoricalSeed(template, year, yearIndex, slot);
  });
});

const allIncidentSeeds = [...generatedHistoricalSeeds, ...incidentSeeds].sort(
  (left, right) => new Date(left.date).getTime() - new Date(right.date).getTime(),
);

export const mockIncidents: Incident[] = allIncidentSeeds.map(buildIncident);
