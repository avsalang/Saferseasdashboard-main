import {chromium} from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const base=process.env.BASE_URL||'http://127.0.0.1:5174/'
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',error=>errors.push(error.message))
const field=label=>page.locator('.q-field').filter({has:page.locator('.q-field__label').filter({hasText:new RegExp('^'+label.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'$')})})
const fill=(label,value)=>field(label).locator('input:visible,textarea:visible').first().fill(value)
const step=async name=>{await page.locator('.q-stepper__tab').filter({hasText:name}).click();await page.waitForTimeout(350)}
try{
 await page.goto(base,{waitUntil:'networkidle'})
 await page.getByRole('button',{name:'MRO Reporter MRO-IV',exact:true}).click()
 await page.goto(base+'#/reporter/reports/new')
 await page.getByRole('heading',{name:'New incident report'}).waitFor()
 assert.equal(await page.locator('.q-stepper__tab').count(),7,'retain seven original reporting sections')
 await fill('Occurrence date','2026-11-05');await fill('Reported place / location *','Fictional test harbor')
 await step('Vessel & Operator');await fill('Vessel name *','MV Fictional Test')
 await step('Voyage & Cargo');await fill('Voyage origin','Fictional origin');await fill('Cargo type','General cargo')
 await field('Crew aboard').locator('..').getByRole('checkbox',{name:'Unknown',exact:true}).uncheck()
 await fill('Crew aboard','0')
 await field('Passengers aboard').locator('..').getByRole('checkbox',{name:'Unknown',exact:true}).uncheck()
 await fill('Passengers aboard','3');await page.getByRole('button',{name:'Use calculated total',exact:true}).click()
 await step('Narrative & Timeline')
 await fill('Factual account / description *','Fictional account, original intake retained with MAIC additions.')
 await fill('Key events timeline','08:30 assistance requested; 09:00 rescue arrived.')
 await fill('Crew behavior / response','Crew accounted for and passengers assisted.')
 await fill('Potential causes (preliminary)','Under assessment; propulsion reported lost.')
 await fill('Rescue, recovery and salvage','Assistance by a fictional rescue vessel.')
 await step('Findings & Outcomes')
 await fill('Findings of cause','Preliminary finding awaiting supporting records.')
 await fill('Consequence observation / as-of','2026-11-05T10:30')
 await step('Attachments');await fill('Reporting authority','MARINA test office')
 await fill('Document notes','Source reference needs verification.')
 await page.getByRole('button',{name:'Save draft',exact:true}).click();await page.waitForURL('**/edit')
 const id=page.url().split('/').at(-2)
 const event=await page.evaluate(id=>JSON.parse(localStorage.getItem('saferseas-marina-vue-demo-v1')).events.find(e=>e.id===id),id)
 assert.match(event.timeline,/08:30/);assert.match(event.crewResponse,/accounted/);assert.match(event.potentialCauses,/assessment/)
 assert.match(event.rescueRecovery,/fictional rescue/);assert.match(event.findingsOfCause,/Preliminary/)
 assert.equal(event.consequences.observedAt,'2026-11-05T10:30');assert.equal(event.reportingAuthority,'MARINA test office')
 assert.match(event.documentNotes,/verification/);assert.equal(event.consequences.fatalities,null)
 assert.equal(event.consequences.crew,0);assert.equal(event.consequences.passengers,3);assert.equal(event.consequences.totalOnboard,3)
 assert.equal(event.vessels[0].voyage.origin,'Fictional origin');assert.equal(event.vessels[0].voyage.cargoType,'General cargo')
 await page.reload();await step('Narrative & Timeline');assert.match(await field('Key events timeline').locator('textarea').inputValue(),/08:30/)
 await step('Review & Submit');assert.ok(await page.getByText('08:30 assistance requested; 09:00 rescue arrived.',{exact:true}).count())
 await fs.mkdir('test-artifacts',{recursive:true});await page.screenshot({path:'test-artifacts/intake-additions-review.png',fullPage:true})
 assert.deepEqual(errors,[])
 console.log('PASS: original seven sections, added fields saved/reopened/reviewed, unknown counts retained, no runtime errors')
}finally{await browser.close()}
