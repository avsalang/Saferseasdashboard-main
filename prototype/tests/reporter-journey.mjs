check(e.evidenceIds.length===1&&s.evidence.find(x=>x.id===e.evidenceIds[0])?.sourceRef==='QA-EVIDENCE-001','draft retained document metadata and source reference');
check(['fatalities','missing','injured','rescued','totalOnboard','crew','passengers'].every(k=>e.consequences[k]===null),'all untouched consequence counts remain null');
check(e.secondaryTypes.join(',')==='Grounding,Listing','multi-value classifications retained in draft');
await step('Review');await page.getByRole('button',{name:'Submit report',exact:true}).click();
await page.waitForURL('**/'+recordId);
s=await state();e=s.events.find(x=>x.id===recordId);
check(e.status==='submitted'&&s.reports.filter(r=>r.eventId===recordId&&r.type==='spot').length===1,'submission created one retained spot revision');
await page.screenshot({path:out+'/reporter-submitted.png',fullPage:true});
await logout();await login('MRO Reviewer MRO-IV');
await page.goto(BASE+'#/admin/incidents/'+recordId);await page.waitForTimeout(500);
await page.getByRole('button',{name:'Start review',exact:true}).click();
await page.getByRole('button',{name:'Request corrections',exact:true}).click();
await fill('Required correction instructions','QA review: clarify the occurrence location and retain both vessels and the source attachment.');
await page.getByRole('button',{name:'Send request',exact:true}).click();
await page.waitForTimeout(500);
s=await state();e=s.events.find(x=>x.id===recordId);
check(e.status==='correction_requested','staff correction request changed event status');
check(s.notifications.some(n=>n.userId==='u-reporter'&&n.link==='/reporter/reports/'+recordId&&n.title==='Correction requested'),'correction notified report owner');
await logout();await login('MRO Reporter MRO-IV');
await page.goto(BASE+'#/reporter/reports/'+recordId);await page.waitForTimeout(400);
await page.getByRole('link',{name:'Respond to correction',exact:true}).click();
await fill('Reported place / location *','QA fictional harbor approach, east of breakwater');
await step('Sources');
check(await page.getByText('QA fictional source statement',{exact:false}).count()>=1,'correction editor displays retained evidence');
await step('Review');await page.getByRole('button',{name:'Resubmit report',exact:true}).click();
await page.waitForURL('**/'+recordId);
s=await state();e=s.events.find(x=>x.id===recordId);
check(e.status==='resubmitted','reporter resubmitted corrected report');
check(e.vessels.length===2&&e.secondaryTypes.join(',')==='Grounding,Listing'&&e.evidenceIds.length===1,'resubmission retained vessels, classifications and evidence');
check(e.consequences.fatalities===null&&e.consequences.injured===null&&e.timeUnknown===true&&e.time===null,'unknown consequences and occurrence time retained');
check(s.reports.filter(r=>r.eventId===recordId&&r.type==='spot').length===2,'resubmission retained both spot-report revisions');
await logout();await login('MRO Reviewer MRO-IV');
await page.goto(BASE+'#/admin/incidents/'+recordId);await page.waitForTimeout(400);
await page.getByRole('button',{name:'Start review',exact:true}).click();
